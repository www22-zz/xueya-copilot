"""Export and verify the generated Hot100 algorithm-demo registry.

The demo frontend (frontend/js/algorithm-lab.js and the practice list badges)
consumes frontend/js/algorithm-demo-registry.js, which is generated from the
backend engine so the frontend never hard-codes a question id.

Usage (from the repository root, any Python 3.11+):

    python scripts/export_algorithm_demos.py --write   # regenerate the file
    python scripts/export_algorithm_demos.py --check   # exit 0 only when current

Both modes really execute the official reference solutions (first sample of
every Hot100 question) through backend.xueya.algorithm_demo, so an id is only
listed when its demo trace is verified against the bank's sample output.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from backend.xueya import algorithm_demo  # noqa: E402

REGISTRY = ROOT / 'frontend' / 'js' / 'algorithm-demo-registry.js'
HEADER = '/* Generated by scripts/export_algorithm_demos.py --write. Do not edit by hand. */'


def render(rows) -> str:
    """Render the deterministic registry file for verified rows (bank order)."""
    ids = [row['id'] for row in rows]
    meta = {}
    for row in rows:
        meta[row['id']] = {
            'viz': row['viz'],
            'title': row['title'],
            'number': row['number'],
            'topic': row['topic'],
        }
    lines = [
        HEADER,
        'window.XueyaAlgorithmDemoIds=' + json.dumps(ids, ensure_ascii=False, separators=(',', ':')) + ';',
        'window.XueyaAlgorithmDemoMeta=' + json.dumps(meta, ensure_ascii=False, separators=(',', ':')) + ';',
        '',
    ]
    return '\n'.join(lines)


def load_rows():
    return algorithm_demo.describe_all(verify=True)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description='Export or verify the algorithm demo registry.')
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--write', action='store_true', help='regenerate the registry file')
    group.add_argument('--check', action='store_true', help='verify the checked-in registry file is current')
    args = parser.parse_args(argv)

    rows = load_rows()
    verified = [row for row in rows if row.get('verified')]
    failed = [row for row in rows if not row.get('verified')]
    text = render(verified)

    print('engine: backend/xueya/algorithm_demo.py (demo-2)')
    print('hot100 questions: %d, verified demos: %d, failed: %d'
          % (len(rows), len(verified), len(failed)))
    for row in failed:
        print('  FAILED %s #%s %s -> %s %s'
              % (row['id'], row.get('number'), row.get('title', ''),
                 row.get('error'), (row.get('detail') or '')[:160]))

    if args.write:
        REGISTRY.parent.mkdir(parents=True, exist_ok=True)
        REGISTRY.write_text(text, encoding='utf-8')
        print('wrote %s (%d ids)' % (REGISTRY.relative_to(ROOT).as_posix(), len(verified)))
        return 0 if not failed else 2

    if not REGISTRY.exists():
        print('MISSING %s; run --write' % REGISTRY.relative_to(ROOT).as_posix())
        return 1
    current = REGISTRY.read_text(encoding='utf-8').replace('\r\n', '\n')
    if current.strip() != text.strip():
        print('STALE %s; run --write' % REGISTRY.relative_to(ROOT).as_posix())
        return 1
    if failed:
        print('REGISTRY CURRENT but %d question(s) failed verification; see list above.' % len(failed))
        return 2
    print('REGISTRY CURRENT: %s (%d ids)' % (REGISTRY.relative_to(ROOT).as_posix(), len(verified)))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
